def expand(patterns: list[str]) -> set[str]:
    out: set[str] = set()
    codes = all_codenames()
    for p in patterns:
        if p.endswith(".*"):
            out |= {c for c in codes if c.startswith(p[:-1])}
        elif p in codes:
            out.add(p)
    return out
